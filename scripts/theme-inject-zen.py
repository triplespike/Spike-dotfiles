#!/usr/bin/env python3
"""Generate theme-colors.css and self-contained newtab/index.html for Zen Browser."""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path


def normalize_hex(val: str, fallback: str) -> str:
    raw = (val or fallback).strip().lstrip("#")
    if len(raw) >= 6:
        return f"#{raw[:6].upper()}"
    return fallback


def hex_to_rgb(hex_color: str) -> tuple[int, int, int]:
    h = hex_color.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def adjust_hex(hex_color: str, delta: int) -> str:
    r, g, b = hex_to_rgb(hex_color)
    r = max(0, min(255, r + delta))
    g = max(0, min(255, g + delta))
    b = max(0, min(255, b + delta))
    return f"#{r:02X}{g:02X}{b:02X}"


def rgba(hex_color: str, alpha: float) -> str:
    r, g, b = hex_to_rgb(hex_color)
    return f"rgba({r}, {g}, {b}, {alpha:.2f})"


def mix_hex(c1: str, c2: str, ratio: float) -> str:
    r1, g1, b1 = hex_to_rgb(c1)
    r2, g2, b2 = hex_to_rgb(c2)
    r = round(r1 * (1 - ratio) + r2 * ratio)
    g = round(g1 * (1 - ratio) + g2 * ratio)
    b = round(b1 * (1 - ratio) + b2 * ratio)
    return f"#{r:02X}{g:02X}{b:02X}"


def luminance(hex_color: str) -> float:
    r, g, b = hex_to_rgb(hex_color)
    return (0.299 * r + 0.587 * g + 0.114 * b) / 255.0


def ensure_visible_accent(color: str, fg: str) -> str:
    """Lift very dark accents (e.g. charcoal presets) so borders/glow remain visible."""
    if luminance(color) < 0.34:
        return mix_hex(color, fg, 0.35)
    return color


def extract_tokens(preset: dict) -> dict[str, str]:
    name = preset.get("name") or preset.get("id") or "Nullscapes"
    ghostty = preset.get("ghostty") or {}
    niri = preset.get("niri") or {}
    ring = niri.get("focus_ring") or {}

    bg = normalize_hex(ghostty.get("background", ""), "#080B16")
    fg = normalize_hex(ghostty.get("foreground", ""), "#E8EDFF")
    raw_primary = normalize_hex(ring.get("from", ""), "#678FE4")
    raw_accent = normalize_hex(ring.get("to", ""), "#AB66CC")
    primary = ensure_visible_accent(raw_primary, fg)
    accent = ensure_visible_accent(raw_accent, fg)
    sel_bg = normalize_hex(ghostty.get("selection_background", ""), "#344879")

    return {
        "name": name,
        "id": preset.get("id", "unknown"),
        "bg": bg,
        "fg": fg,
        "primary": primary,
        "accent": accent,
        "sel_bg": sel_bg,
        "surface": adjust_hex(bg, 14),
        "surface_alt": adjust_hex(bg, 24),
        "fg_muted": mix_hex(fg, bg, 0.36),
        "tinted_bg": mix_hex(bg, primary, 0.08),
        "outline_variant": mix_hex(bg, primary, 0.34),
    }


def build_palette(tokens: dict[str, str]) -> dict[str, str]:
    return {
        "surface": tokens["bg"],
        "onSurface": tokens["fg"],
        "surfaceContainer": tokens["surface"],
        "surfaceContainerHigh": tokens["surface_alt"],
        "outlineVariant": tokens["outline_variant"],
        "outline": tokens["primary"],
        "primary": tokens["primary"],
        "primaryContainer": tokens["sel_bg"],
        "onPrimaryContainer": "#FFFFFF",
        "tertiary": tokens["accent"],
    }


def build_css(tokens: dict[str, str]) -> str:
    safe_label = tokens["name"].replace('"', '\\"')
    bg = tokens["bg"]
    fg = tokens["fg"]
    primary = tokens["primary"]
    accent = tokens["accent"]
    sel_bg = tokens["sel_bg"]
    surface = tokens["surface"]
    surface_alt = tokens["surface_alt"]
    fg_muted = tokens["fg_muted"]
    tinted_bg = tokens["tinted_bg"]

    return f"""/* Auto-generated by theme-inject-zen for preset: {tokens["id"]} */
:root {{
  --zen-theme-label: "{safe_label}";

  --zen-bg: {bg};
  --zen-bg-translucent: {rgba(tinted_bg, 0.80)};
  --zen-sidebar-bg: {rgba(surface, 0.72)};
  --zen-toolbar-bg: {rgba(tinted_bg, 0.76)};
  --zen-surface: {surface};
  --zen-surface-alt: {surface_alt};
  --zen-surface-hover: {rgba(sel_bg, 0.65)};
  --zen-urlbar-bg: {rgba(surface, 0.88)};

  --zen-fg: {fg};
  --zen-fg-muted: {fg_muted};
  --zen-primary: {primary};
  --zen-accent: {accent};

  --zen-border: {rgba(primary, 0.34)};
  --zen-border-contrast: {rgba(accent, 0.48)};
  --zen-glow: {rgba(primary, 0.32)};
  --zen-shadow: rgba(0, 0, 0, 0.62);
  --zen-border-radius: 14px;
}}
"""


def write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        path.unlink()
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(content, encoding="utf-8")
    tmp.replace(path)


def main() -> int:
    home = Path(os.environ.get("HOME", Path.home()))
    presets_file = home / ".config/theme-manager/presets.json"
    current_file = home / ".local/state/theme-manager/current"

    target_id = sys.argv[1].strip() if len(sys.argv) > 1 and sys.argv[1].strip() else ""
    if not target_id and current_file.exists():
        target_id = current_file.read_text(encoding="utf-8").strip()
    if not target_id:
        target_id = "nullscapes"

    preset: dict = {"id": "nullscapes", "name": "Nullscapes (Cosmic Neon)"}
    if presets_file.exists():
        try:
            data = json.loads(presets_file.read_text(encoding="utf-8"))
            presets = data.get("presets", [])
            preset = next((p for p in presets if p.get("id") == target_id), None) or (
                presets[0] if presets else preset
            )
        except (OSError, json.JSONDecodeError):
            pass

    tokens = extract_tokens(preset)
    css = build_css(tokens)

    zen_profiles: list[Path] = []
    for base in (home / ".config/zen", home / ".zen"):
        if not base.is_dir():
            continue
        for entry in sorted(base.iterdir()):
            if entry.is_dir() and ((entry / "prefs.js").exists() or (entry / "chrome").is_dir()):
                zen_profiles.append(entry)
    for prof in zen_profiles:
        write_atomic(prof / "chrome/theme-colors.css", css)

    write_atomic(
        home / ".cache/theme-manager/zen-palette.json",
        json.dumps(build_palette(tokens), indent=2, ensure_ascii=False) + "\n",
    )

    template_env = os.environ.get("ZEN_NEWTAB_TEMPLATE", "").strip()
    candidates = [
        Path(template_env) if template_env else None,
        Path(__file__).resolve().parent.parent / "zen-newtab/index.html",
        home / ".config/theme-manager/zen-newtab.html",
    ]
    template_path = next((p for p in candidates if p is not None and p.exists()), None)
    if template_path is not None:
        html = template_path.read_text(encoding="utf-8")
        injected = re.sub(
            r'<style id="theme-vars">.*?</style>',
            f'<style id="theme-vars">\n{css}\n  </style>',
            html,
            count=1,
            flags=re.DOTALL,
        )
        write_atomic(home / ".config/zen/newtab/index.html", injected)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
