#!/usr/bin/env python3
"""Sync Vesktop, VSCode, and Firefox themes with Theme Manager presets."""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path


def normalize_hex(val: str, fallback: str) -> str:
    raw = (val or fallback).strip().lstrip("#")
    if len(raw) >= 6:
        return f"#{raw[:6].upper()}"
    return fallback


def hex_to_rgb(hex_color: str) -> tuple[int, int, int]:
    h = hex_color.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def adjust_hex(hex_color: str, delta: int) -> str:
    r, g, b = hex_to_rgb(hex_color)
    r = max(0, min(255, r + delta))
    g = max(0, min(255, g + delta))
    b = max(0, min(255, b + delta))
    return f"#{r:02X}{g:02X}{b:02X}"


def rgba(hex_color: str, alpha: float) -> str:
    r, g, b = hex_to_rgb(hex_color)
    return f"rgba({r}, {g}, {b}, {alpha:.2f})"


def mix_hex(c1: str, c2: str, ratio: float) -> str:
    r1, g1, b1 = hex_to_rgb(c1)
    r2, g2, b2 = hex_to_rgb(c2)
    r = round(r1 * (1 - ratio) + r2 * ratio)
    g = round(g1 * (1 - ratio) + g2 * ratio)
    b = round(b1 * (1 - ratio) + b2 * ratio)
    return f"#{r:02X}{g:02X}{b:02X}"


def luminance(hex_color: str) -> float:
    r, g, b = hex_to_rgb(hex_color)
    return (0.299 * r + 0.587 * g + 0.114 * b) / 255.0


def ensure_visible_accent(color: str, fg: str) -> str:
    if luminance(color) < 0.34:
        return mix_hex(color, fg, 0.35)
    return color


def write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        path.unlink()
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(content, encoding="utf-8")
    tmp.replace(path)


def extract_palette(preset: dict) -> dict[str, str]:
    ghostty = preset.get("ghostty") or {}
    niri = preset.get("niri") or {}
    ring = niri.get("focus_ring") or {}
    palette = ghostty.get("palette") or []

    bg = normalize_hex(ghostty.get("background", ""), "#080B16")
    fg = normalize_hex(ghostty.get("foreground", ""), "#E8EDFF")
    primary = ensure_visible_accent(normalize_hex(ring.get("from", ""), "#678FE4"), fg)
    accent = ensure_visible_accent(normalize_hex(ring.get("to", ""), "#AB66CC"), fg)
    sel_bg = normalize_hex(ghostty.get("selection_background", ""), "#344879")

    danger = "#FD4663"
    positive = "#7DCFFF"
    for entry in palette:
        if isinstance(entry, str) and entry.startswith("1="):
            danger = normalize_hex(entry[2:], danger)
        elif isinstance(entry, str) and entry.startswith("10="):
            positive = normalize_hex(entry[3:], positive)

    return {
        "id": preset.get("id", "nullscapes"),
        "name": preset.get("name", "Nullscapes"),
        "bg": bg,
        "bg_sec": adjust_hex(bg, 6),
        "bg_alt": adjust_hex(bg, 10),
        "surface": adjust_hex(bg, 14),
        "surface_alt": adjust_hex(bg, 22),
        "fg": fg,
        "fg_muted": mix_hex(fg, bg, 0.35),
        "primary": primary,
        "primary_hover": adjust_hex(primary, -18),
        "primary_active": adjust_hex(primary, -34),
        "accent": accent,
        "sel_bg": sel_bg,
        "danger": danger,
        "positive": positive,
    }


